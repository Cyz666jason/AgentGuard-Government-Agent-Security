"""Remote Streamable HTTP MCP endpoint for OpenClaw.

This is a deliberately small, dependency-free resource server.  It reuses the
existing :class:`~integrations.openclaw_mcp.server.McpServer` JSON-RPC/tool
implementation and sends every tool call through an operator-supplied
AgentGuard ``invoke`` callable.  The callable is always invoked with
``authorization_header=None``: an external OAuth access token is used only to
derive a verified subject and is never forwarded to a business endpoint.

The class is suitable for local tests and for embedding behind a TLS reverse
proxy.  It does not pretend to terminate TLS itself; a public deployment must
put it behind HTTPS/mTLS and configure a real OIDC verifier and audit sink.
"""

